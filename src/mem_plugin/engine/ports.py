"""Persistence contract; implementations live in infrastructure."""

from collections.abc import Callable
from datetime import datetime
from types import TracebackType
from typing import Protocol, Self
from uuid import UUID

from mem_plugin.engine.models import (
    AccessContext,
    ArchiveManifest,
    ChatResult,
    ClaimedTask,
    EmbeddingResult,
    LifecyclePolicy,
    MemoryNode,
    MemoryTask,
    MemoryVersion,
    SearchFilters,
    SemanticRelation,
    VectorMatch,
)
from mem_plugin.observability.models import AuditEvent


class NodeRepository(Protocol):
    def ids(self, limit: int) -> tuple[UUID, ...]: ...
    def insert(self, node: MemoryNode) -> MemoryNode: ...
    def get(self, node_id: UUID, *, lock: bool = False) -> MemoryNode | None: ...
    def publish(self, node: MemoryNode, expected_version: int) -> None: ...
    def search(
        self, query: str, limit: int, filters: SearchFilters | None = None
    ) -> list[MemoryNode]: ...
    def confirm(self, node_id: UUID) -> None: ...
    def invalidate(self, node_ids: tuple[UUID, ...]) -> None: ...
    def forget(self, node_ids: tuple[UUID, ...]) -> None: ...
    def clear_hidden_context_dependents(self, node_ids: tuple[UUID, ...]) -> tuple[UUID, ...]: ...
    def lexical(
        self, query: str, limit: int, filters: SearchFilters, threshold: float
    ) -> list[MemoryNode]: ...
    def eligible(self, node_ids: tuple[UUID, ...], filters: SearchFilters) -> list[MemoryNode]: ...
    def embedding_failed(self, node_id: UUID, version: int) -> bool: ...
    def evolve_context(self, node: MemoryNode, context: str) -> MemoryNode: ...
    def mark_dirty(self, node_ids: tuple[UUID, ...], *, bump: bool = False) -> list[MemoryNode]: ...
    def settle_dirty(self, node_id: UUID, *, blocked: bool = False) -> None: ...


class GraphRepository(Protocol):
    def lock_scope(self) -> None: ...
    def hierarchy(self, child: MemoryNode, parent: MemoryNode) -> bool: ...
    def semantic(self, source: MemoryNode, target: MemoryNode, relation: str) -> bool: ...
    def correction_family(self, node_id: UUID) -> tuple[UUID, ...]: ...
    def ancestors(self, node_ids: tuple[UUID, ...]) -> tuple[UUID, ...]: ...
    def associate(self, relation: SemanticRelation) -> bool: ...
    def relations(
        self, node_id: UUID, *, active_only: bool = False
    ) -> tuple[SemanticRelation, ...]: ...
    def context_neighbors(self, node_ids: tuple[UUID, ...]) -> tuple[UUID, ...]: ...
    def parents(self, node_id: UUID) -> list[MemoryNode]: ...
    def replace_sources(self, node_id: UUID, source_ids: tuple[UUID, ...]) -> None: ...


class VersionRepository(Protocol):
    def append(self, version: MemoryVersion) -> None: ...
    def get(self, node_id: UUID, version: int) -> MemoryVersion | None: ...
    def evidence(self, node_id: UUID, version: int) -> tuple[MemoryNode, ...]: ...


class ConsolidationRepository(Protocol):
    def suppress(self, node_id: UUID) -> None: ...
    def suppressed(self, node_id: UUID) -> bool: ...
    def members(self, node_id: UUID) -> list[MemoryNode]: ...
    def groups(self, seed: MemoryNode, target_level: int, limit: int) -> list[MemoryNode]: ...
    def due(self, target_level: int, limit: int) -> list[MemoryNode]: ...


class LifecycleRepository(Protocol):
    def due(self, now: datetime, policy: LifecyclePolicy, limit: int) -> list[MemoryNode]: ...
    def snapshot(self, node: MemoryNode) -> tuple[dict[str, object], ...]: ...
    def manifest(self, node_id: UUID) -> ArchiveManifest | None: ...
    def reserve(self, manifest: ArchiveManifest) -> None: ...
    def finish_archive(self, node: MemoryNode) -> None: ...
    def restore(self, node: MemoryNode, status: str, now: datetime) -> None: ...
    def update(
        self,
        node: MemoryNode,
        *,
        expire: bool,
        review: bool,
        confidence: float | None,
        decay_at: datetime | None,
    ) -> None: ...
    def remove_manifest(self, node_id: UUID) -> None: ...
    def related_archives(self, node_ids: tuple[UUID, ...]) -> list[ArchiveManifest]: ...
    def invalidate_manifest(self, node_id: UUID, removed_ids: tuple[UUID, ...]) -> None: ...


class ArchiveStore(Protocol):
    def write(self, key: str, payload: bytes) -> None: ...
    def read(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...


class AuditRepository(Protocol):
    def append(self, event: AuditEvent) -> None: ...


class OutboxRepository(Protocol):
    def append(self, task: MemoryTask) -> None: ...
    def lock_claim(self, task: ClaimedTask) -> bool: ...
    def was_applied(self, task: ClaimedTask) -> bool: ...
    def complete(self, task: ClaimedTask) -> bool: ...
    def fail(self, task: ClaimedTask, error_type: str, retry_delay: float | None) -> bool: ...


class VectorRepository(Protocol):
    def save(
        self, node_id: UUID, version: int, content_hash: str, vector: tuple[float, ...]
    ) -> None: ...
    def search(
        self, vector: tuple[float, ...], limit: int = 20, filters: SearchFilters | None = None
    ) -> list[VectorMatch]: ...
    def matches(self, node_id: UUID, version: int, content_hash: str) -> bool: ...
    def candidates(
        self, node: MemoryNode, limit: int, max_distance: float, *, same_level: bool = False
    ) -> list[VectorMatch]: ...


class UnitOfWork(Protocol):
    nodes: NodeRepository
    graph: GraphRepository
    versions: VersionRepository
    audit: AuditRepository
    outbox: OutboxRepository
    vectors: VectorRepository
    consolidation: ConsolidationRepository
    lifecycle: LifecycleRepository

    def __enter__(self) -> Self: ...
    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        traceback: TracebackType | None,
    ) -> None: ...
    def commit(self) -> None: ...


UnitOfWorkFactory = Callable[[AccessContext], UnitOfWork]


class LLMProvider(Protocol):
    provider: str
    model: str

    def complete(
        self, messages: list[dict[str, str]], *, max_output_tokens: int | None = None
    ) -> ChatResult: ...


class EmbeddingProvider(Protocol):
    provider: str
    model: str

    def embed(self, text: str) -> EmbeddingResult: ...


class RerankProvider(Protocol):
    provider: str
    model: str

    def rerank(self, query: str, documents: list[str]) -> list[tuple[int, float]]: ...


class TaskQueue(Protocol):
    def claim(
        self,
        worker_id: str,
        lease_seconds: float,
        event_types: tuple[str, ...] = ("embedding.requested",),
    ) -> ClaimedTask | None: ...


class TaskHandler(Protocol):
    def execute(self, task: ClaimedTask) -> str: ...
    def failure(self, task: ClaimedTask, error_type: str, retry_delay: float | None) -> str: ...
